// `npm run brand` regenerates the React brand components from webAsset/ SVGs.
import { readFileSync, writeFileSync } from "node:fs";

const HEADER = "// Generated by scripts/build-brand.ts from webAsset/. Do not edit by hand.\n";

/* ----- plain logo: letter paths only ----- */
const logoSvg = readFileSync("webAsset/logo/tmii-logo.svg", "utf8");
const logoViewBox = logoSvg.match(/viewBox="([^"]+)"/)![1];
const letters = [...logoSvg.matchAll(/<path id="(letter-[^"]+)"[^>]* d="([^"]+)"/g)].map((m) => ({ id: m[1], d: m[2] }));
writeFileSync(
  "src/components/brand/logo-paths.ts",
  `${HEADER}export const LOGO_VIEWBOX = ${JSON.stringify(logoViewBox)};\nexport const LOGO_LETTERS = ${JSON.stringify(letters, null, 2)} as const;\n`,
);

/* ----- decorated logo: full markup as JSX ----- */
const decorated = readFileSync("webAsset/decoration/tmii-decorated.svg", "utf8");
const viewBox = decorated.match(/viewBox="([^"]+)"/)![1];
let body = decorated.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();

body = body
  .replace(/<title>[^<]*<\/title>\s*/, "")
  // The clip path keeps a real (prefixed) id; everything else becomes data-part.
  .replace('id="carousel-roof-clip"', "id={`${p}-carousel-roof-clip`}")
  .replace('clip-path="url(#carousel-roof-clip)"', "clipPath={`url(#${p}-carousel-roof-clip)`}")
  .replace(/ id="([^"]+)"/g, ' data-part="$1"')
  .replace(/ class="/g, ' className="')
  .replace(/ stroke-width=/g, " strokeWidth=")
  .replace(/ stroke-linecap=/g, " strokeLinecap=")
  .replace(/ stroke-linejoin=/g, " strokeLinejoin=")
  .replace(/ stroke-dasharray=/g, " strokeDasharray=");

// Snake segments: the first path is the body (drawn on), the second the spots.
body = body.replace(
  /(<g className="snake-seg"[^>]*>\s*)<path ([^>]*)\/>\s*<path ([^>]*)\/>/g,
  '$1<path className="snake-body" pathLength={1} $2/>\n      <path className="snake-spots" $3/>',
);

// Stagger leaves with a CSS custom property.
let leafIndex = 0;
body = body.replace(/className="leaf"/g, () => `className="leaf" style={{ "--i": ${leafIndex++} } as CSSProperties}`);

writeFileSync(
  "src/components/brand/decorated-logo-svg.tsx",
  `${HEADER}import type { CSSProperties } from "react";

export const DECORATED_VIEWBOX = ${JSON.stringify(viewBox)};

/** The decorated logo markup. \`p\` namespaces the clip-path id when rendered more than once. */
export function DecoratedLogoMarkup({ p }: { p: string }) {
  return (
    <>
${body
  .split("\n")
  .map((line) => `      ${line}`)
  .join("\n")}
    </>
  );
}
`,
);
console.log(`logo: ${letters.length} letters · decorated: ${leafIndex} leaves`);
